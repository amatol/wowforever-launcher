let lang = 'ru';

/// fr, en, es or pt from a setting ('' = system language) or a browser language tag.
function resolveLanguage(setting) {
  const wanted = setting ? [setting] : navigator.languages || [navigator.language];
  for (const tag of wanted) {
    const code = String(tag).slice(0, 2).toLowerCase();
    if (code === 'ru' || code === 'en') return code;
  }
  return 'en';
}

function t(key, vars = {}) {
  const text = TEXTS[lang][key] ?? TEXTS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}

function applyLanguage(code) {
  lang = code;
  document.documentElement.lang = code;
  document.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
}
